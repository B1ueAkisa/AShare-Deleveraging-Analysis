def format_time(sec):
    h = int(sec // 3600)
    m = int((sec % 3600) // 60)
    s = int(sec % 60)
    ms = int((sec - int(sec)) * 1000)
    return f"{h:02d}:{m:02d}:{s:02d},{ms:03d}"

srt_entries = []
count = 1

for sid, start, dur, text in SCENE_TIMES:
    # Split text by sentence terminators
    sentences = re.split(r'([。？！；，])', text)
    chunks = []
    curr = ""
    for token in sentences:
        curr += token
        if token in ('。', '？', '！', '；') or len(curr) > 20:
            if curr.strip():
                chunks.append(curr.strip())
            curr = ""
    if curr.strip():
        chunks.append(curr.strip())
        
    total_chars = sum(len(c) for c in chunks)
    curr_time = start
    for c in chunks:
        c_dur = dur * (len(c) / total_chars)
        t_start = curr_time
        t_end = curr_time + c_dur
        curr_time = t_end
        
        srt_entries.append(f"{count}\n{format_time(t_start)} --> {format_time(t_end)}\n{c}\n")
        count += 1

with open(OUT_SRT, "w", encoding="utf-8") as f:
    f.write("\n".join(srt_entries))

